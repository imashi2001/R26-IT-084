def _holiday_records_for_date(holiday_by_year: Dict[int, List[HolidayRecord]], d: Date) -> List[HolidayRecord]:
    """Return holiday records that match this date."""

    records = holiday_by_year.get(d.year, [])
    iso = d.isoformat()
    return [r for r in records if r.iso_date == iso]


def _is_poya_holiday_name(name: str) -> bool:
    return "poya" in name.lower()


def _is_festival_holiday_name(name: str) -> bool:
    # Heuristic: many holidays include 'Festival', 'Eid', 'Christmas', etc.
    lowered = name.lower()
    return any(
        kw in lowered
        for kw in [
            "festival",
            "vesak",
            "poson",
            "esala",
            "deepavali",
            "diwali",
            "thai pongal",
            "eid",
            "christmas",
            "new year",
        ]
    )


def is_event_day(holiday_by_year: Dict[int, List[HolidayRecord]], target_date: Date) -> EventFlags:
    """Determine whether the date is a Poya day, a public holiday, or part of a long weekend.

    Long-weekend rule (requested example):
    - If Friday is a holiday, treat Fri/Sat/Sun as high-impact.
    - If Monday is a holiday, treat Sat/Sun/Mon as high-impact.
    """

    todays = _holiday_records_for_date(holiday_by_year, target_date)
    holiday_names = tuple(sorted({r.name for r in todays}))

    is_poya = any(_is_poya_holiday_name(r.name) for r in todays)

    # Treat anything returned by Calendarific as a public holiday for this research-oriented dashboard.
    # We also mark days as public-holiday-like if they look like festivals.
    is_public_holiday = bool(todays) or any(_is_festival_holiday_name(n) for n in holiday_names)

    # Long weekend detection (requested example logic)
    # - If Friday is a holiday => Fri/Sat/Sun become high-impact
    # - If Monday is a holiday => Sat/Sun/Mon become high-impact
    is_long_weekend = False

    weekday = target_date.weekday()  # Mon=0 ... Sun=6

    def has_holiday(d: Date) -> bool:
        return bool(_holiday_records_for_date(holiday_by_year, d))

    # Friday-anchored long weekend
    if weekday in (4, 5, 6):
        friday = target_date - timedelta(days=(weekday - 4))
        if has_holiday(friday):
            is_long_weekend = True

    # Monday-anchored long weekend
    if weekday in (5, 6, 0):
        if weekday == 0:
            monday = target_date
        elif weekday == 5:  # Saturday
            monday = target_date + timedelta(days=2)
        else:  # Sunday
            monday = target_date + timedelta(days=1)

        if has_holiday(monday):
            is_long_weekend = True

    return EventFlags(
        is_public_holiday=is_public_holiday,
        is_poya=is_poya,
        is_long_weekend=is_long_weekend,
        holiday_names=holiday_names,
    )



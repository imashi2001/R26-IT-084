def _calendarific_api_key() -> Optional[str]:
    """Get Calendarific API key from env.

    For security, do not hardcode secrets in production.
    """

    key = os.getenv("CALENDARIFIC_API_KEY", "").strip()
    return key or None


def _parse_calendarific_holidays(payload: Dict[str, Any]) -> List[HolidayRecord]:
    """Parse Calendarific response into HolidayRecord list."""

    holidays: List[HolidayRecord] = []
    response = payload.get("response", {})
    for h in response.get("holidays", []) or []:
        try:
            name = str(h.get("name", "")).strip()
            iso_date = str(((h.get("date") or {}).get("iso", ""))).strip()
            types = h.get("type") or []
            primary_type = str(types[0]) if types else "Unknown"

            if name and iso_date:
                holidays.append(HolidayRecord(name=name, iso_date=iso_date, primary_type=primary_type))
        except Exception:  # noqa: BLE001
            continue

    return holidays


def fetch_sri_lanka_holidays(years: List[int]) -> Dict[int, List[HolidayRecord]]:
    """Fetch Sri Lanka holidays for the specified years from Calendarific.

    Requirements implemented:
    - Robust error handling for API requests
    - Uses cache to avoid repeated API calls
    """

    # Load cache
    cached = _load_json(HOLIDAY_CACHE_PATH)
    holiday_by_year: Dict[int, List[HolidayRecord]] = {}

    # Hydrate from cache
    for year_str, records in (cached or {}).items():
        try:
            y = int(year_str)
            holiday_by_year[y] = [HolidayRecord(**r) for r in (records or [])]
        except Exception:  # noqa: BLE001
            continue

    api_key = _calendarific_api_key()
    if not api_key:
        logger.warning(
            "Calendarific API key not found. Set CALENDARIFIC_API_KEY to enable holiday detection."
        )
        return holiday_by_year

    updated = False

    for year in years:
        if year in holiday_by_year and holiday_by_year[year]:
            continue

        try:
            with _HOLIDAY_FETCH_LOCK:
                resp = requests.get(
                    CALENDARIFIC_BASE_URL,
                    params={
                        "api_key": api_key,
                        "country": CALENDARIFIC_COUNTRY,
                        "year": year,
                    },
                    timeout=20,
                )
            if resp.status_code != 200:
                logger.warning("Calendarific returned %s: %s", resp.status_code, resp.text[:300])
                continue

            payload = resp.json()
            records = _parse_calendarific_holidays(payload)
            holiday_by_year[year] = records
            updated = True
            logger.info("Fetched %d holidays for Sri Lanka (%d)", len(records), year)

        except requests.RequestException as ex:
            logger.warning("Calendarific request error for year %d: %s", year, ex)
        except Exception as ex:  # noqa: BLE001
            logger.exception("Unexpected Calendarific failure for year %d: %s", year, ex)

    if updated:
        # Save to disk in serializable form
        serializable = {
            str(y): [r.__dict__ for r in rs]
            for y, rs in holiday_by_year.items()
            if rs
        }
        _save_json(HOLIDAY_CACHE_PATH, serializable)

    return holiday_by_year



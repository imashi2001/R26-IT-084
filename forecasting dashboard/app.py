def _stable_rng(location_name: str, d: Date) -> random.Random:
    """Stable RNG so the same date/location yields the same output (reproducibility)."""

    seed = f"{location_name}|{d.isoformat()}"
    return random.Random(seed)


def _rand_int(rng: random.Random, lo: int, hi: int) -> int:
    return int(rng.randint(lo, hi))


def calculate_waste_impact(
    location_name: str,
    d: Date,
    flags: EventFlags,
) -> int:
    """Calculate predicted waste fill level (0-100) for a location and date.

    Rules implemented from prompt:
    - Religious Sites: If Poya or Festival -> 90-100%
    - Transport Hubs: If Sunday or Public Holiday -> 85-95%
    - Recreational Parks: If Weekend -> 80-90%
    - Seasonal (Sri Pada/Nallathanniya): Dec-May baseline 80%, spike to 100% on Poya
    - Default baseline: 30-50%

    We also treat "long weekend" as holiday-like, increasing impact.
    """

    rng = _stable_rng(location_name, d)
    weekday = d.weekday()  # Mon=0 ... Sun=6
    is_weekend = weekday in (5, 6)
    is_sunday = weekday == 6

    # Treat long weekend as high-impact holiday context
    holiday_like = flags.is_public_holiday or flags.is_long_weekend
    festival_like = flags.is_poya or flags.is_public_holiday

    # Seasonal pilgrimage logic has priority for Sri Pada
    if location_name in SEASONAL_PILGRIMAGE:
        in_season = d.month in (12, 1, 2, 3, 4, 5)
        if in_season:
            if flags.is_poya:
                return 100
            # Baseline 80% (slight variability for realism)
            return _rand_int(rng, 78, 85)

        # Off-season: calmer baseline
        return _rand_int(rng, 35, 55)

    # Religious sites
    if location_name in RELIGIOUS_SITES:
        if flags.is_poya or festival_like:
            return _rand_int(rng, 90, 100)
        return _rand_int(rng, 35, 55)

    # Transport hubs
    if location_name in TRANSPORT_HUBS:
        if is_sunday or holiday_like:
            return _rand_int(rng, 85, 95)
        return _rand_int(rng, 40, 60)

    # Recreational parks
    if location_name in RECREATIONAL_PARKS:
        if is_weekend:
            return _rand_int(rng, 80, 90)
        return _rand_int(rng, 35, 55)

    # Default
    return _rand_int(rng, 30, 50)



def _load_json(path: Path) -> Dict[str, Any]:
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception as ex:  # noqa: BLE001
        logger.warning("Failed to read JSON cache %s: %s", path, ex)
        return {}


def _save_json(path: Path, payload: Dict[str, Any]) -> None:
    try:
        path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    except Exception as ex:  # noqa: BLE001
        logger.warning("Failed to write JSON cache %s: %s", path, ex)


def geocode_landmarks(landmarks: List[str]) -> Dict[str, Tuple[float, float]]:
    """Geocode landmarks via Nominatim with 1-second delay and caching.

    Returns a dict mapping location_name -> (lat, lon) for successfully geocoded locations.

    Implementation details:
    - Uses time.sleep(1) between API calls (Nominatim rate limiting)
    - Uses in-memory dict cache, with optional persistence to JSON for faster restarts
    - Robust error handling: failures are logged and skipped
    """

    # Load persisted cache first (dictionary cache requirement is still met; this is just persistence)
    persisted_cache = _load_json(GEOCODE_CACHE_PATH)

    # In-memory cache (requested)
    coords_cache: Dict[str, Tuple[float, float]] = {}

    # Hydrate from disk
    for k, v in persisted_cache.items():
        try:
            coords_cache[k] = (float(v[0]), float(v[1]))
        except Exception:  # noqa: BLE001
            continue

    # Create a descriptive user_agent as recommended by Nominatim
    geolocator = Nominatim(user_agent="spatio_temporal_waste_analytics_dashboard")

    updated = False
    for name in landmarks:
        if name in coords_cache:
            continue

        # Try aliases first (more reliable), then fallback query.
        queries = GEOCODE_ALIASES.get(name, []) + [f"{name}, Sri Lanka"]
        try:
            # Respect Nominatim usage policy and prevent concurrent requests.

            location = None
            for query in queries:
                with _GEOCODE_REQUEST_LOCK:
                    time.sleep(1)
                    location = geolocator.geocode(query, timeout=15)

                if location is not None:
                    break

            if location is None:
                logger.warning("Geocoding returned no result for: %s", queries[0])
                continue

            coords_cache[name] = (float(location.latitude), float(location.longitude))
            updated = True
            logger.info("Geocoded %s -> (%.6f, %.6f)", name, location.latitude, location.longitude)

        except (GeocoderTimedOut, GeocoderServiceError) as ex:
            logger.warning("Geocoding error for %s: %s", query, ex)
        except Exception as ex:  # noqa: BLE001
            logger.exception("Unexpected geocoding failure for %s: %s", query, ex)

    if updated:
        _save_json(GEOCODE_CACHE_PATH, {k: list(v) for k, v in coords_cache.items()})

    return coords_cache


def load_geocode_cache() -> Dict[str, Tuple[float, float]]:
    """Load geocode cache from disk without making network calls."""

    persisted_cache = _load_json(GEOCODE_CACHE_PATH)
    coords_cache: Dict[str, Tuple[float, float]] = {}
    for k, v in persisted_cache.items():
        try:
            coords_cache[k] = (float(v[0]), float(v[1]))
        except Exception:  # noqa: BLE001
            continue
    return coords_cache



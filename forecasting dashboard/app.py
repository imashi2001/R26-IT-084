@dataclass(frozen=True)
class EventFlags:
    """Flags describing how "eventful" a day is for waste generation."""

    is_public_holiday: bool
    is_poya: bool
    is_long_weekend: bool
    holiday_names: Tuple[str, ...]

    def summary_text(self) -> str:
        if not (self.is_public_holiday or self.is_poya or self.is_long_weekend):
            return "Normal day (no holiday detected)"

        labels: List[str] = []
        if self.is_poya:
            labels.append("Poya")
        if self.is_public_holiday:
            labels.append("Public Holiday")
        if self.is_long_weekend:
            labels.append("Long Weekend")

        names = ", ".join(self.holiday_names) if self.holiday_names else "—"
        return f"{' / '.join(labels)} | {names}"



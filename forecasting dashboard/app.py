@app.callback(
    Output("card-selected-date", "children"),
    Output("card-holiday-status", "children"),
    Output("card-global-average", "children"),
    Output("heatmap", "figure"),
    Output("insights-list", "children"),
    Input("date-picker", "date"),
)
def update_dashboard(date_str: Optional[str]):
    """Update the dashboard when the date changes."""

    if not date_str:
        selected = Date.today()
    else:
        try:
            selected = datetime.fromisoformat(date_str).date()
        except Exception:
            selected = Date.today()

    rows, flags = _compute_rows_for_date(selected)

    # If holiday data for this year isn't loaded yet, present a "loading" hint.
    with _HOLIDAYS_LOCK:
        holiday_year_ready = selected.year in HOLIDAYS_BY_YEAR and bool(HOLIDAYS_BY_YEAR.get(selected.year))

    holiday_text = flags.summary_text() if holiday_year_ready else "Loading holiday data…"

    # If any landmarks are missing coordinates, geocoding might still be in progress.
    with _COORDS_LOCK:
        missing_count = sum(1 for l in LANDMARKS if l not in COORDS)

    if rows:
        avg = sum(r["fill_level"] for r in rows) / len(rows)
        avg_text = f"{avg:.1f}%"
    else:
        avg_text = "—"

    fig = build_map_figure(rows) if rows else go.Figure()
    if not rows:
        fig.update_layout(
            annotations=[
                dict(
                    text="No geocoded points available (check geocoding + internet access).",
                    x=0.5,
                    y=0.5,
                    showarrow=False,
                    xref="paper",
                    yref="paper",
                )
            ]
        )
    elif missing_count:
        fig.update_layout(
            annotations=[
                dict(
                    text=f"Geocoding in progress for {missing_count} location(s)…",
                    x=0.5,
                    y=0.02,
                    showarrow=False,
                    xref="paper",
                    yref="paper",
                    font=dict(size=12, color="#555"),
                )
            ]
        )

    insights = build_actionable_insights(rows)

    return (
        _fmt_date(date_str),
        holiday_text,
        avg_text,
        fig,
        insights,
    )



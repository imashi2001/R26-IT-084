def build_actionable_insights(rows: List[Dict[str, Any]]) -> List[html.Li]:
    """Generate actionable insights for the sidebar."""

    items: List[html.Li] = []

    # Sort descending by fill level
    sorted_rows = sorted(rows, key=lambda r: r["fill_level"], reverse=True)

    for r in sorted_rows:
        loc = r["location"]
        lvl = int(r["fill_level"])

        if lvl >= 90:
            bins = 5
            items.append(
                html.Li(
                    [
                        "⚠️ ",
                        html.B(f"ALERT: {loc}"),
                        f" exceeding 90% threshold ({lvl}%). ",
                        html.I(f"Recommended: Deploy {bins} temporary bins."),
                    ]
                )
            )
        elif lvl >= 80:
            bins = 3
            items.append(
                html.Li(
                    [
                        "⚠️ ",
                        html.B(f"WATCH: {loc}"),
                        f" high utilization ({lvl}%). ",
                        html.I(f"Recommended: Add {bins} extra bins and increase collection frequency."),
                    ]
                )
            )

    if not items:
        items.append(html.Li("No critical alerts for the selected date. Maintain standard operations."))

    return items


